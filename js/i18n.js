let currentLang = localStorage.getItem('niffer_lang') || 'en';

function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('niffer_lang', lang);
  document.documentElement.lang = lang;
  document.getElementById('langLabel') && (document.getElementById('langLabel').textContent = lang.toUpperCase());
  applyTranslations();
}

function t(key) {
  return translations[currentLang][key] || translations.en[key] || key;
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[currentLang][key]) {
      el.textContent = translations[currentLang][key];
    }
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (translations[currentLang][key]) {
      el.placeholder = translations[currentLang][key];
    }
  });
}

// Toggle language
document.addEventListener('DOMContentLoaded', () => {
  const toggle = document.getElementById('langToggle');
  if (toggle) {
    toggle.addEventListener('click', () => {
      setLanguage(currentLang === 'en' ? 'sw' : 'en');
    });
  }
  setLanguage(currentLang);
});
