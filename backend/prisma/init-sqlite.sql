-- Emish Beauty Spa — SQLite schema (Termux workaround when prisma db push fails)

PRAGMA foreign_keys = ON;

CREATE TABLE IF NOT EXISTS User (
  id TEXT PRIMARY KEY NOT NULL,
  phone TEXT NOT NULL UNIQUE,
  email TEXT UNIQUE,
  name TEXT NOT NULL,
  passwordHash TEXT,
  role TEXT NOT NULL DEFAULT 'CUSTOMER',
  referralCode TEXT NOT NULL UNIQUE,
  referredById TEXT,
  isActive INTEGER NOT NULL DEFAULT 1,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (referredById) REFERENCES User(id)
);

CREATE TABLE IF NOT EXISTS Address (
  id TEXT PRIMARY KEY NOT NULL,
  userId TEXT NOT NULL,
  label TEXT,
  fullName TEXT NOT NULL,
  phone TEXT NOT NULL,
  addressLine TEXT NOT NULL,
  city TEXT NOT NULL,
  region TEXT,
  isDefault INTEGER NOT NULL DEFAULT 0,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (userId) REFERENCES User(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS Category (
  id TEXT PRIMARY KEY NOT NULL,
  slug TEXT NOT NULL UNIQUE,
  nameEn TEXT NOT NULL,
  nameSw TEXT NOT NULL,
  description TEXT,
  imageUrl TEXT,
  sortOrder INTEGER NOT NULL DEFAULT 0,
  isActive INTEGER NOT NULL DEFAULT 1,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS Product (
  id TEXT PRIMARY KEY NOT NULL,
  slug TEXT NOT NULL UNIQUE,
  nameEn TEXT NOT NULL,
  nameSw TEXT NOT NULL,
  descriptionEn TEXT NOT NULL,
  descriptionSw TEXT NOT NULL,
  howToUseEn TEXT,
  howToUseSw TEXT,
  ingredients TEXT,
  price INTEGER NOT NULL,
  compareAtPrice INTEGER,
  sku TEXT UNIQUE,
  stock INTEGER NOT NULL DEFAULT 0,
  lowStockThreshold INTEGER NOT NULL DEFAULT 5,
  categoryId TEXT NOT NULL,
  images TEXT NOT NULL,
  badge TEXT,
  rating REAL NOT NULL DEFAULT 0,
  reviewCount INTEGER NOT NULL DEFAULT 0,
  isActive INTEGER NOT NULL DEFAULT 1,
  isFeatured INTEGER NOT NULL DEFAULT 0,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (categoryId) REFERENCES Category(id)
);

CREATE TABLE IF NOT EXISTS CartItem (
  id TEXT PRIMARY KEY NOT NULL,
  userId TEXT NOT NULL,
  productId TEXT NOT NULL,
  quantity INTEGER NOT NULL DEFAULT 1,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(userId, productId),
  FOREIGN KEY (userId) REFERENCES User(id) ON DELETE CASCADE,
  FOREIGN KEY (productId) REFERENCES Product(id)
);

CREATE TABLE IF NOT EXISTS "Order" (
  id TEXT PRIMARY KEY NOT NULL,
  orderNumber TEXT NOT NULL UNIQUE,
  userId TEXT,
  status TEXT NOT NULL DEFAULT 'PENDING',
  customerName TEXT NOT NULL,
  customerPhone TEXT NOT NULL,
  customerEmail TEXT,
  shippingAddress TEXT NOT NULL,
  shippingCity TEXT NOT NULL,
  shippingRegion TEXT,
  notes TEXT,
  subtotal INTEGER NOT NULL,
  shippingFee INTEGER NOT NULL DEFAULT 0,
  discount INTEGER NOT NULL DEFAULT 0,
  total INTEGER NOT NULL,
  referralCodeUsed TEXT,
  paymentMethod TEXT,
  paymentStatus TEXT NOT NULL DEFAULT 'PENDING',
  pesapalTrackingId TEXT,
  pesapalMerchantRef TEXT,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  paidAt DATETIME,
  FOREIGN KEY (userId) REFERENCES User(id)
);

CREATE TABLE IF NOT EXISTS OrderItem (
  id TEXT PRIMARY KEY NOT NULL,
  orderId TEXT NOT NULL,
  productId TEXT NOT NULL,
  productName TEXT NOT NULL,
  quantity INTEGER NOT NULL,
  unitPrice INTEGER NOT NULL,
  totalPrice INTEGER NOT NULL,
  FOREIGN KEY (orderId) REFERENCES "Order"(id) ON DELETE CASCADE,
  FOREIGN KEY (productId) REFERENCES Product(id)
);

CREATE TABLE IF NOT EXISTS Commission (
  id TEXT PRIMARY KEY NOT NULL,
  userId TEXT NOT NULL,
  orderId TEXT NOT NULL,
  amount INTEGER NOT NULL,
  rate REAL NOT NULL,
  status TEXT NOT NULL DEFAULT 'PENDING',
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  paidAt DATETIME,
  FOREIGN KEY (userId) REFERENCES User(id),
  FOREIGN KEY (orderId) REFERENCES "Order"(id)
);

CREATE TABLE IF NOT EXISTS Setting (
  id TEXT PRIMARY KEY NOT NULL,
  key TEXT NOT NULL UNIQUE,
  value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS ServiceCategory (
  id TEXT PRIMARY KEY NOT NULL,
  slug TEXT NOT NULL UNIQUE,
  nameEn TEXT NOT NULL,
  nameSw TEXT NOT NULL,
  description TEXT,
  sortOrder INTEGER NOT NULL DEFAULT 0,
  isActive INTEGER NOT NULL DEFAULT 1,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS Service (
  id TEXT PRIMARY KEY NOT NULL,
  slug TEXT NOT NULL UNIQUE,
  nameEn TEXT NOT NULL,
  nameSw TEXT NOT NULL,
  descriptionEn TEXT NOT NULL,
  descriptionSw TEXT NOT NULL,
  durationMinutes INTEGER NOT NULL DEFAULT 60,
  price INTEGER NOT NULL,
  compareAtPrice INTEGER,
  imageUrl TEXT,
  categoryId TEXT NOT NULL,
  isActive INTEGER NOT NULL DEFAULT 1,
  isFeatured INTEGER NOT NULL DEFAULT 0,
  sortOrder INTEGER NOT NULL DEFAULT 0,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (categoryId) REFERENCES ServiceCategory(id)
);

CREATE TABLE IF NOT EXISTS Booking (
  id TEXT PRIMARY KEY NOT NULL,
  bookingNumber TEXT NOT NULL UNIQUE,
  serviceId TEXT NOT NULL,
  userId TEXT,
  customerName TEXT NOT NULL,
  customerPhone TEXT NOT NULL,
  customerEmail TEXT,
  scheduledAt DATETIME NOT NULL,
  durationMinutes INTEGER NOT NULL,
  status TEXT NOT NULL DEFAULT 'PENDING',
  notes TEXT,
  price INTEGER NOT NULL,
  paymentStatus TEXT NOT NULL DEFAULT 'PENDING',
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (serviceId) REFERENCES Service(id),
  FOREIGN KEY (userId) REFERENCES User(id)
);
